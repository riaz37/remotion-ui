#!/usr/bin/env node
/**
 * gen-cli-files.mjs: writes src/generated/cli-files.ts.
 *
 * The film's file cards show the real source that `npx remotion-ui@latest add
 * intro` writes. The CLI copies registry files verbatim (checked with diff
 * against a real install), so this reads them straight from the registry.
 *
 * The order and install paths below are the CLI's real output order, captured
 * from a run of packages/remotion-ui (v0.9.1) against a fresh `init` project.
 *
 *     node showcase/remotionui-launch/scripts/gen-cli-files.mjs   # from apps/web
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "../../..");
const registry = path.join(appRoot, "registry/bases/default");

const FILES = [
  ["src/remotion/lib/code-syntax.tsx", "lib/code-syntax.tsx"],
  ["src/remotion/lib/layout.ts", "lib/layout.ts"],
  ["src/remotion/lib/timing.ts", "lib/timing.ts"],
  ["src/remotion/lib/motion-tokens.ts", "lib/motion-tokens.ts"],
  ["src/remotion/scenes/title-card/index.tsx", "scenes/title-card/index.tsx"],
  ["src/remotion/lib/motion-wrapper.tsx", "lib/motion-wrapper.tsx"],
  ["src/remotion/primitives/fade-out.tsx", "primitives/fade-out.tsx"],
  ["src/compositions/intro/index.tsx", "compositions/intro/index.tsx"],
];

const LINES = 16;

/** First LINES lines of code, skipping comment blocks and blank runs. */
const excerpt = (source) => {
  const out = [];
  let inBlock = false;
  for (const raw of source.split("\n")) {
    const line = raw.replace(/\t/g, "  ");
    const t = line.trim();
    if (inBlock) {
      if (t.includes("*/")) inBlock = false;
      continue;
    }
    if (t.startsWith("/*")) {
      inBlock = !t.includes("*/");
      continue;
    }
    if (t.startsWith("//")) continue;
    if (t === "" && (out.length === 0 || out[out.length - 1] === "")) continue;
    out.push(line.length > 58 ? `${line.slice(0, 57)}…` : line);
    if (out.length >= LINES) break;
  }
  return out;
};

const entries = FILES.map(([installPath, registryPath]) => {
  const source = fs.readFileSync(path.join(registry, registryPath), "utf8");
  return { path: installPath, lines: source.split("\n").length, excerpt: excerpt(source) };
});

const outDir = path.join(here, "../src/generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, "cli-files.ts"),
  `/* Generated by scripts/gen-cli-files.mjs. Do not edit by hand. */\n\nexport type CliFile = { path: string; lines: number; excerpt: string[] };\n\nexport const CLI_FILES: CliFile[] = ${JSON.stringify(entries, null, 2)};\n`,
);
console.log(`wrote ${entries.length} files`);
